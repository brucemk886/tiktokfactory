import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const output=path.join(root,'factory-cloud/src/ui-asset-manifest.js');
// Only tracked UI code/styles/icons. Never expose HTML, uploads, JSON or runtime artifacts.
const paths=execFileSync('git',['ls-files','-z','public'],{cwd:root,encoding:'utf8'}).split('\0').filter(p=>/^public\/[^/]+\.(js|css)$/.test(p)||/^public\/vendor\/bootstrap-icons\/[^/]+\.svg$/.test(p)).sort();
const versions=Object.fromEntries(paths.filter(p=>!p.startsWith('public/psychology-topics.')).map(p=>['/'+p.slice(7),createHash('sha256').update(fs.readFileSync(path.join(root,p),'utf8').replace(/\r\n/g,'\n')).digest('hex').slice(0,20)]));
const text='// Generated by npm run assets:manifest. Commit with UI changes.\nexport const UI_ASSETS = '+JSON.stringify(versions,null,2)+';\n';
if(process.argv.includes('--check')){
 if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==text)throw new Error('UI asset manifest is stale. Run npm run assets:manifest in factory-cloud and commit it.');
}else fs.writeFileSync(output,text);
